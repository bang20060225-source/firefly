/** 책 페이지 번호처럼 보이게 하는 숫자 (장식용) */
export function pageNumber(index: number): number {
  return ((index * 37 + 11) % 180) + 3
}

/**
 * 한 번 나온 글귀는 모든 글귀가 한 번씩 나올 때까지 다시 나오지 않는 '섞인 순서'.
 * 기록은 저장하지 않는다. (앱을 새로 열면 새로 섞인다)
 */
export function createLineBag(count: number, rng: () => number = Math.random) {
  let order: number[] = []
  let last = -1
  return function next(): number {
    if (order.length === 0) {
      order = Array.from({ length: count }, (_, i) => i)
      for (let i = order.length - 1; i > 0; i--) {
        const j = Math.floor(rng() * (i + 1))
        ;[order[i], order[j]] = [order[j], order[i]]
      }
      // 새로 섞었을 때 방금 본 글귀가 맨 앞에 오지 않게
      if (order[order.length - 1] === last && order.length > 1) {
        ;[order[0], order[order.length - 1]] = [order[order.length - 1], order[0]]
      }
    }
    last = order.pop() as number
    return last
  }
}
